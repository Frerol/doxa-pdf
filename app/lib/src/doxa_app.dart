/// Seed color of the Doxa PDF Material 3 theme (docs/plan/05-ux-design.md §5).
const Color doxaSeedColor = Color(0xFF7048E8);

Future<PdfEngine>? _pdfium;

/// The app's PDFium engine, started on first use and kept for the app's
/// lifetime (one engine per process).
/// A failed start is not kept, so the next call tries again.
Future<PdfEngine> loadPdfiumEngine() =>
    _pdfium ??= PdfiumEngine.spawn().catchError((Object error) {
      _pdfium = null;
      throw error;
    });

/// Reads the system accent colour, or null where there is none.
typedef AccentColorLoader = Future<Color?> Function();

/// Root widget of Doxa PDF.
class DoxaApp extends StatefulWidget {
  const DoxaApp({
    super.key,
    this.engine = loadPdfiumEngine,
    this.devDocumentsDir,
    this.settings,
    this.accentColor,
    this.pdfDocuments,
  });

  final Future<PdfEngine> Function() engine;
  final PdfDocuments? pdfDocuments;

  /// App settings; in memory only when null (tests).
  final SettingsController? settings;

  /// The system accent colour for dynamic colour (FR-SET-001), read again
  /// whenever the app comes back to the foreground (the wallpaper may have
  /// changed).
  final AccentColorLoader? accentColor;

  /// Folder listed by the temporary developer document list; by default the
  /// app's own folder on Android, and none elsewhere.
  final String? devDocumentsDir;

  @override
  State<DoxaApp> createState() => _DoxaAppState();
}

class _DoxaAppState extends State<DoxaApp> with WidgetsBindingObserver {
  SettingsController? _ownSettings;
  Color? _accent;

  SettingsController get settings =>
      widget.settings ??
      (_ownSettings ??= SettingsController(MemorySettingsStore()));

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
    _loadAccent();
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed) _loadAccent();
  }

  void _loadAccent() {
    final loader = widget.accentColor;
    if (loader == null) return;
    loader().then((color) {
      if (mounted && color != _accent) setState(() => _accent = color);
    }, onError: (Object _) {});
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _ownSettings?.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder(
      valueListenable: settings,
      builder: (context, value, _) => _app(value),
    );
  }

  Widget _app(AppSettings value) {
    final seed = value.dynamicColor
        ? (_accent ?? doxaSeedColor)
        : doxaSeedColor;
    final code = value.languageCode;
    return MaterialApp(
      onGenerateTitle: (context) => AppLocalizations.of(context).appTitle,
      themeMode: value.themeMode,
      theme: ThemeData(colorSchemeSeed: seed),
      darkTheme: ThemeData(colorSchemeSeed: seed, brightness: Brightness.dark),
      locale: code == null ? null : Locale(code),
      // Flutter 3.47+ moved Material/Cupertino out of the SDK. The delegate
      // list generated by gen-l10n still points at flutter_localizations, so
      // use material_ui's own delegates instead.
      localizationsDelegates: const [
        AppLocalizations.delegate,
        ...GlobalMaterialLocalizations.delegates,
      ],
      supportedLocales: AppLocalizations.supportedLocales,
      home: PlaceholderHome(
        engine: widget.engine,
        pdfDocuments:
            widget.pdfDocuments ??
            (Platform.isAndroid ? DoxaPlatform().pdfDocuments : null),
        settings: settings,
        devDocumentsDir:
            widget.devDocumentsDir ??
            (Platform.isAndroid ? androidDevDocumentsDir : null),
      ),
    );
  }
}

/// Temporary home screen until the library (M1) exists.
class PlaceholderHome extends StatefulWidget {
  const PlaceholderHome({
    super.key,
    required this.engine,
    required this.settings,
    this.devDocumentsDir,
    this.pdfDocuments,
  });

  final Future<PdfEngine> Function() engine;
  final SettingsController settings;
  final String? devDocumentsDir;

  final PdfDocuments? pdfDocuments;

  @override
  State<PlaceholderHome> createState() => _PlaceholderHomeState();
}

class _PlaceholderHomeState extends State<PlaceholderHome> {
  StreamSubscription<void>? _incoming;
  bool _draining = false;
  bool _incomingPending = false;
  bool _picking = false;

  @override
  void initState() {
    super.initState();
    _incoming = widget.pdfDocuments?.incomingPdfs.listen((_) => _onIncoming());
    WidgetsBinding.instance.addPostFrameCallback((_) => _onIncoming());
  }

  @override
  void dispose() {
    unawaited(_incoming?.cancel());
    super.dispose();
  }

  void _onIncoming() {
    _incomingPending = true;
    if (!_draining && mounted) unawaited(_drainIncoming());
  }

  Future<void> _drainIncoming() async {
    final documents = widget.pdfDocuments;
    if (documents == null) return;
    _draining = true;
    try {
      while (mounted && _incomingPending) {
        _incomingPending = false;
        while (mounted) {
          try {
            final pdf = await documents.takeIncomingPdf();
            if (pdf == null) break;
            await _showPdf(documents, pdf);
          } on PdfAccessException catch (error) {
            _showAccessError(error.error);
          }
        }
      }
    } on Object catch (error) {
      debugPrint('Doxa: cannot receive PDFs: $error');
      _showAccessError(PdfAccessError.unreadable);
    } finally {
      _draining = false;
    }
  }

  Future<void> _pick() async {
    final documents = widget.pdfDocuments!;
    setState(() => _picking = true);
    try {
      final pdf = await documents.pickPdf();
      if (pdf != null) await _showPdf(documents, pdf);
    } on PdfAccessException catch (error) {
      _showAccessError(error.error);
    } on Object catch (error) {
      debugPrint('Doxa: PDF picker failed: $error');
      _showAccessError(PdfAccessError.unreadable);
    } finally {
      if (mounted) setState(() => _picking = false);
    }
  }

  Future<void> _showPdf(PdfDocuments documents, PlatformPdf pdf) async {
    if (!mounted) {
      await documents.releasePdf(pdf.leaseId);
      return;
    }
    final engine = widget.engine;
    final settings = widget.settings;
    Future<PdfEngine>? readerEngine;
    final route = MaterialPageRoute<void>(
      builder: (_) {
        return ReaderPage(
          engine: readerEngine ??= Future.sync(engine),
          source: FileSource(pdf.path),
          title: pdf.displayName,
          settings: settings,
          releaseSource: () => documents.releasePdf(pdf.leaseId),
        );
      },
    );
    unawaited(
      Navigator.of(context).push(route).then((_) async {
        if (readerEngine == null) await documents.releasePdf(pdf.leaseId);
      }),
    );
  }

  void _showAccessError(PdfAccessError error) {
    if (!mounted) return;
    final l10n = AppLocalizations.of(context);
    final message = switch (error) {
      PdfAccessError.missing => l10n.fileMissing,
      PdfAccessError.unreadable => l10n.fileUnreadable,
      PdfAccessError.notPdf => l10n.fileNotPdf,
      PdfAccessError.permissionLost => l10n.filePermissionLost,
    };
    ScaffoldMessenger.of(context)
        .showSnackBar(SnackBar(content: Text(message)));
  }

  @override
  Widget build(BuildContext context) {
    final l10n = AppLocalizations.of(context);
    final textTheme = Theme.of(context).textTheme;
    return Scaffold(
      appBar: AppBar(
        actions: [
          IconButton(
            icon: const Icon(Icons.settings_outlined),
            tooltip: l10n.settingsTitle,
            onPressed: () => Navigator.of(context).push(
              MaterialPageRoute<void>(
                builder: (_) => SettingsPage(settings: widget.settings),
              ),
            ),
          ),
        ],
      ),
      body: Center(
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(24),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Image.asset(
                'assets/brand/doxa-glyph.png',
                width: 96,
                height: 96,
                excludeFromSemantics: true,
              ),
              Text(l10n.appTitle, style: textTheme.displaySmall),
              const SizedBox(height: 8),
              Text(l10n.homeTagline, style: textTheme.titleMedium),
              const SizedBox(height: 24),
              Text(l10n.previewNotice, textAlign: TextAlign.center),
              if (widget.pdfDocuments != null) ...[
                const SizedBox(height: 24),
                FilledButton.icon(
                  onPressed: _picking ? null : _pick,
                  icon: const Icon(Icons.folder_open),
                  label: Text(l10n.openFile),
                ),
              ],
              if (widget.devDocumentsDir case final dir?) ...[
                const SizedBox(height: 24),
                DevDocuments(
                  engine: widget.engine,
                  directory: dir,
                  settings: widget.settings,
                ),
              ],
            ],
          ),
        ),
      ),
    );
  }
}
